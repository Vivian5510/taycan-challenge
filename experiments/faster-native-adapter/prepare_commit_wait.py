"""Extract the pinned RocksDB 8.9.1 wait handshake, preserving its algorithm."""
from pathlib import Path
import hashlib

def generate(destination):
    root=Path(__file__).resolve().parents[2]
    original=root/'research/rocksdb-v8.9.1/db/write_thread.cc'
    source=original.read_text()
    methods=source[source.index('uint8_t WriteThread::BlockingAwaitState('):source.index('bool WriteThread::LinkOne(')]
    # Keep upstream's state handshake and adaptive-yield algorithm; omit only
    # DB perf counters and its test synchronization callback.
    methods=methods.replace('WriteThread::','CommitWait::')
    methods=methods.replace('  PERF_TIMER_GUARD(write_thread_wait_nanos);','')
    methods=methods.replace('    TEST_SYNC_POINT_CALLBACK("CommitWait::AwaitState:BlockingWaiting", w);','')
    methods=methods.replace('uint8_t CommitWait::','inline uint8_t CommitWait::').replace('void CommitWait::','inline void CommitWait::')
    header='''// Copyright (c) 2011-present, Facebook, Inc. All rights reserved.
// Derived from RocksDB 8.9.1 write_thread.cc (Apache-2.0; LICENSE.RocksDB.Apache).
// Generated by prepare_commit_wait.py. Only the class name and instrumentation
// hooks differ in the extracted methods. Writer/AdaptationContext are upstream.
#pragma once
#include "db/write_thread.h"
#include "port/port.h"
#include "util/random.h"
#include <chrono>
#include <thread>
namespace reference {
namespace port = ROCKSDB_NAMESPACE::port;
using ROCKSDB_NAMESPACE::Random;
class CommitWait {
 public:
  using Writer=ROCKSDB_NAMESPACE::WriteThread::Writer;
  using AdaptationContext=ROCKSDB_NAMESPACE::WriteThread::AdaptationContext;
  static constexpr uint8_t STATE_LOCKED_WAITING=ROCKSDB_NAMESPACE::WriteThread::STATE_LOCKED_WAITING;
  static constexpr uint8_t STATE_COMPLETED=ROCKSDB_NAMESPACE::WriteThread::STATE_COMPLETED;
  void Wait(Writer* w) {AwaitState(w,STATE_COMPLETED,&context_);}
  void Complete(Writer* w) {SetState(w,STATE_COMPLETED);}
 private:
  uint8_t BlockingAwaitState(Writer* w,uint8_t goal_mask);
  uint8_t AwaitState(Writer* w,uint8_t goal_mask,AdaptationContext* ctx);
  void SetState(Writer* w,uint8_t new_state);
  uint64_t max_yield_usec_=F2_WRITE_ADAPTIVE_YIELD?F2_WRITE_MAX_YIELD_US:0;
  uint64_t slow_yield_usec_=3;
  AdaptationContext context_{"F2PrefixCommit"};
};
'''
    destination.write_text(header+methods+'\n} // namespace reference\n')
    license_path=root/'research/rocksdb-v8.9.1/LICENSE.Apache'
    (destination.parent/'LICENSE.RocksDB.Apache').write_bytes(license_path.read_bytes())
    (destination.parent/'commit-wait-provenance.txt').write_text(
        'RocksDB commit 49ce8a1064dd1ad89117899839bf136365e49e79\nwrite_thread.cc sha256 '+hashlib.sha256(original.read_bytes()).hexdigest()+'\n')
